'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'rasta-core.js'),'utf8');
const context={location:{pathname:'/index.html'}};
vm.createContext(context);
new vm.Script(source,{filename:'rasta-core.js'}).runInContext(context);
const core=context.RastaCore;
assert.ok(core,'RastaCore must expose a public API');
assert.equal(core.version,'1.0.0');
assert.equal(core.config.supabase.url,'https://ptmokqppwjjxhakjpxum.supabase.co');
assert.ok(core.config.supabase.publishableKey.startsWith('sb_publishable_'));
assert.equal(Object.isFrozen(core.config.supabase),true);
assert.equal(core.health().status,'ready');
assert.ok(core.listModules().some(item=>item.id==='app-shell'));
const first=core.registerModule('test-engine',{kind:'engine',version:'1.2.3',dependencies:['app-shell']});
assert.equal(first.status,'ready');
assert.deepEqual(Array.from(first.dependencies),['app-shell']);
core.registerModule('test-dependent-engine',{kind:'engine',version:'1.0.0',dependencies:['missing-test-dependency']});
const missingHealth=core.health();
assert.equal(missingHealth.status,'degraded','health must degrade when a registered module dependency is missing');
assert.deepEqual(Array.from(missingHealth.missingDependencies, item => ({module:item.module,dependency:item.dependency})),[{module:'test-dependent-engine',dependency:'missing-test-dependency'}]);
core.registerModule('missing-test-dependency',{kind:'service',version:'1.0.0'});
assert.equal(core.health().status,'ready','health must recover after a missing dependency is registered');
assert.equal(core.health().missingDependencies.length,0);
const seen=[];const off=core.on('test:event',value=>seen.push(value));
assert.equal(core.emit('test:event',{ok:true}),1);assert.equal(seen[0].ok,true);
off();assert.equal(core.emit('test:event',{ok:false}),0);
core.registerModule('test-engine-consumer',{kind:'engine',version:'1.0.0',dependencies:['test-engine']});
core.setModuleStatus('test-engine','degraded','simulated_test_issue');
assert.equal(core.health().status,'degraded');
assert.ok(Array.from(core.health().unhealthyDependencies).some(item=>item.module==='test-engine-consumer'&&item.dependency==='test-engine'&&item.status==='degraded'),'health must identify dependencies whose registered module is unhealthy');
core.setModuleStatus('test-engine','ready','simulated_test_recovery');
assert.equal(core.health().status,'ready');
assert.equal(core.health().unhealthyDependencies.length,0,'health must recover when a dependency becomes ready');
core.reportError('simulated_error',new Error('do-not-store-this-message'),'test-engine');
const last=core.recentEvents().at(-1);
assert.equal(last.code,'simulated_error');assert.equal(last.errorType,'Error');
assert.equal(JSON.stringify(last).includes('do-not-store-this-message'),false);
assert.equal(source.includes('service_role'),false,'browser core must not contain a service-role credential');
console.log('Rasta Core tests passed.');
